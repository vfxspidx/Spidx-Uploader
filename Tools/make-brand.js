"use strict";

/* Builds App\brand.js (the Spidx logo as small data: URIs for the Dashboard and the setup wizard:
 * browser-tab icon + header logo) from Tools\brand\logo-256.png. Uses sharp, which the app already depends on.
 *     cd App && npm install --omit=dev --ignore-scripts      (once)
 *     node ..\Tools\make-brand.js
 */
const fs = require("fs");
const path = require("path");
const sharp = require(path.join(__dirname, "..", "App", "node_modules", "sharp"));

const SRC = path.join(__dirname, "brand", "logo-256.png");
const OUT = path.join(__dirname, "..", "App", "brand.js");

async function uri(size) {
    const png = await sharp(SRC).resize(size, size, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png({ compressionLevel: 9 }).toBuffer();
    return "data:image/png;base64," + png.toString("base64");
}

(async () => {
    const favicon = await uri(64);   // browser tab
    const logo = await uri(96);      // header (shown at 34 px, crisp on high-DPI screens)
    fs.writeFileSync(OUT, `"use strict";\n\n// Generated by Tools/make-brand.js from Tools/brand/logo-256.png - do not edit by hand.\n\nconst FAVICON = ${JSON.stringify(favicon)};\nconst LOGO = ${JSON.stringify(logo)};\n\nmodule.exports = { FAVICON, LOGO };\n`);
    console.log("Wrote " + OUT + " (favicon " + Math.round(favicon.length / 1024) + " KB, logo " + Math.round(logo.length / 1024) + " KB as text)");
})().catch(err => { console.error(err.message); process.exit(1); });
